'use strict';
const fs=require('node:fs');
const path=require('node:path');
const Ajv=require('ajv');
const standalone=require('ajv/dist/standalone').default;
const schema=require('../config/extraction.schema.json');
const root=path.resolve(__dirname,'..');
const ajv=new Ajv({strict:true,allErrors:false,code:{source:true}});
const code=standalone(ajv,ajv.compile(schema));
fs.mkdirSync(path.join(root,'src','generated'),{recursive:true});
fs.writeFileSync(path.join(root,'src','generated','extraction-validator.cjs'),'// Generated from config/extraction.schema.json by scripts/build-schema.cjs\n'+code);
const dynamic=require('../src/dynamic-api.cjs').schema;
const dynamicAjv=new Ajv({strict:true,allErrors:false,code:{source:true}});
fs.writeFileSync(path.join(root,'src','generated','dynamic-validator.cjs'),'// Generated by scripts/build-schema.cjs\n'+standalone(dynamicAjv,dynamicAjv.compile(dynamic)));
console.log('Extraction JSON Schema compiled to static JavaScript');
const production=require('../src/production.cjs').schema;
const productionAjv=new Ajv({strict:true,allErrors:false,code:{source:true}});
fs.writeFileSync(path.join(root,'src','generated','production-validator.cjs'),'// Generated by scripts/build-schema.cjs\n'+standalone(productionAjv,productionAjv.compile(production)));
const review=require('../src/production.cjs').reviewSchema,reviewAjv=new Ajv({strict:true,allErrors:false,code:{source:true}});
fs.writeFileSync(path.join(root,'src','generated','production-review-validator.cjs'),'// Generated by scripts/build-schema.cjs\n'+standalone(reviewAjv,reviewAjv.compile(review)));
const nativeReading=require('../config/native-reading.schema.json'),nativeAjv=new Ajv({strict:true,allErrors:false,code:{source:true}});
fs.writeFileSync(path.join(root,'src','generated','native-reading-validator.cjs'),'// Generated by scripts/build-schema.cjs\n'+standalone(nativeAjv,nativeAjv.compile(nativeReading)));
const fieldSchema=require('../src/template-fill.cjs').schema,fieldAjv=new Ajv({strict:true,allErrors:false,code:{source:true}});
fs.writeFileSync(path.join(root,'src','generated','template-fields-validator.cjs'),'// Generated by scripts/build-schema.cjs\n'+standalone(fieldAjv,fieldAjv.compile(fieldSchema)));
